from typing import List, Dict, Any
from fastapi import APIRouter, Depends, status
from app.core.security import get_current_user, get_optional_current_user
from app.schemas.risk import (
    RiskPredictionRequest,
    RiskPredictionResponse,
    RiskHistoryItem,
)
from app.services.risk_service import risk_service

router = APIRouter(prefix="/risk", tags=["Risk Analysis"])


@router.post(
    "/predict",
    response_model=RiskPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Predict Agricultural Risk",
    description="Calculate multi-factor agronomic risk assessment, identify contributors, and provide recommendations.",
)
async def predict_risk(
    payload: RiskPredictionRequest,
    current_user: Optional[Dict[str, Any]] = Depends(get_optional_current_user),
) -> Dict[str, Any]:
    user_id = current_user["id"] if current_user else 1
    return risk_service.predict_risk(
        user_id=user_id,
        request=payload,
    )


@router.get(
    "/history",
    response_model=List[RiskHistoryItem],
    status_code=status.HTTP_200_OK,
    summary="Get Risk Prediction History",
    description="Retrieve all past risk prediction summaries generated by the authenticated user.",
)
async def get_risk_history(
    current_user: Optional[Dict[str, Any]] = Depends(get_optional_current_user),
) -> List[Dict[str, Any]]:
    if not current_user:
        return []
    return risk_service.get_user_history(current_user["id"])


@router.get(
    "/history/{prediction_id}",
    response_model=RiskPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Get Risk Prediction Detail",
    description="Retrieve full details for a specific risk prediction assessment by ID.",
)
async def get_risk_detail(
    prediction_id: str,
    current_user: Dict[str, Any] = Depends(get_current_user),
) -> Dict[str, Any]:
    return risk_service.get_prediction_detail(
        user_id=current_user["id"],
        prediction_id=prediction_id,
    )
